/** @type {string} */
let locale = "ko";

export function detectLocale() {
  if (window.ITZ_I18N && typeof window.ITZ_I18N.getLang === "function") {
    const shared = window.ITZ_I18N.getLang();
    if (I18N[shared]) return shared;
  }
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && I18N[saved]) return saved;
  } catch {
    /* ignore */
  }
  const nav = String(navigator.language || "ko").toLowerCase();
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

export function getLocale() {
  return locale;
}

export function numberLocale() {
  return { ko: "ko-KR", en: "en-US", ja: "ja-JP", zh: "zh-CN" }[locale] || "en-US";
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(key, vars) {
  let text = (I18N[locale] && I18N[locale][key]) || I18N.en[key] || I18N.ko[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function applyI18n(next) {
  if (next && I18N[next]) {
    locale = next;
  }
  document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
  document.title = t("title");
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t("description"));
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });
}
