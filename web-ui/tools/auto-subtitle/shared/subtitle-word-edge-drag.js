/** `(lineIndex, wordIndex)` ??`activeIndex` ??. */
export function buildActiveIndexMap(active) {
  const m = new Map();
  for (const a of active) m.set(`${a.lineIndex}:${a.wordIndex}`, a.activeIndex)
  return m
}

