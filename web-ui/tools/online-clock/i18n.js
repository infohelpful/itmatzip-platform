/** @type {Locale} */
let current = "ko";

/** @param {string} raw */
export function normalizeLocale(raw) {
  const v = String(raw || "").toLowerCase();
  if (v.startsWith("ko")) return "ko";
  if (v.startsWith("ja")) return "ja";
  if (v.startsWith("zh")) return "zh";
  if (v.startsWith("en")) return "en";
  return null;
}

function intlLocale() {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || "";
  } catch {
    return "";
  }
}

function browserLanguageCandidates() {
  /** @type {string[]} */
  const list = [];
  const intl = intlLocale();
  if (intl) list.push(intl);
  if (Array.isArray(navigator.languages)) list.push(...navigator.languages);
  if (navigator.language) list.push(navigator.language);
  return list;
}

export function detectLocale() {
  try {
    const saved = normalizeLocale(localStorage.getItem(LANG_KEY) || "");
    if (saved) return saved;
  } catch {
    /* ignore */
  }
  for (const raw of browserLanguageCandidates()) {
    const match = normalizeLocale(raw);
    if (match) return match;
  }
  return "ko";
}

/**
 * @param {Locale} locale
 * @param {{ persist?: boolean }} [opts]
 */
export function setLocale(locale, opts) {
  current = DICT[locale] ? locale : "ko";
  if (opts?.persist) {
    try {
      localStorage.setItem(LANG_KEY, current);
    } catch {
      /* ignore */
    }
  }
  return current;
}

export function getLocale() {
  return current;
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(key, vars) {
  const table = DICT[current] || DICT.ko;
  let text = table[key] ?? DICT.ko[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** @param {ParentNode} [root] */
export function applyI18n(root = document) {
  const htmlLang = { ko: "ko", en: "en", ja: "ja", zh: "zh-CN" };
  document.documentElement.lang = htmlLang[current] || current;
  document.title = t("meta.title");
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t("meta.description"));

  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n") || "");
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder") || ""));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria") || ""));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title") || ""));
  });
}
